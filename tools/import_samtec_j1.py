"""Place Samtec's 3D model of the stacking header J1 (ESQ-108-24-G-D, C21241050) in the footprint's frame.

Source: the STEP model (AP242, generated by TraceParts for Samtec, part version 1.4.6) from the "Download 3D Model"
button on https://www.samtec.com/products/esq-108-24-g-d (downloaded 17 November 2026; Samtec provides it "as is").
In that file the header lies along x (0 .. 20.83), y is up (socket top at y = 8.509, tail ends at y = -14.732, so
the seating plane is at y = 8.509 - 13.59 = -5.081) and the two rows run along z (0 .. 5.08).

The footprint (pcb/p1base.pretty/CoreInk_Bus_2x08_P2.54mm.kicad_mod) has its origin in the middle of the 2 x 8 pins,
rows along y and columns at x = +-1.27; KiCad models have z up with the board's top surface at z = 0. So: rotate the
axes x -> y, y -> z, z -> x (120 deg about (1, 1, 1)) and move the pin field's centre to the origin. The tails (below
the board) are coloured gold, the rest black.

Needs CadQuery:  python tools/import_samtec_j1.py <esq-108-24-g-d.stp>
"""
import os
import sys

import cadquery as cq

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "pcb", "p1base.3dshapes", "Samtec_ESQ-108-24-G-D.step")
SEAT_Y = 8.509 - 13.59  # seating plane in the vendor file
CENTRE = (20.828 / 2, 5.08 / 2)  # pin field centre in the vendor file: x (along the rows), z (between the rows)
BLACK = cq.Color(0.1, 0.1, 0.1)
GOLD = cq.Color(0.85, 0.7, 0.25)


def main(src):
    shape = cq.importers.importStep(src).val()
    b = shape.BoundingBox()
    assert abs(b.ymax - 8.509) < 0.01 and abs(b.ymin + 14.732) < 0.01, f"unexpected vendor frame {b.ymin}..{b.ymax}"
    placed = (shape.translate(cq.Vector(-CENTRE[0], -SEAT_Y, -CENTRE[1]))
              .rotate(cq.Vector(0, 0, 0), cq.Vector(1, 1, 1), 120))
    below = cq.Solid.makeBox(20, 40, 20, cq.Vector(-10, -20, -20.5))  # everything under the board (z < -0.5)
    tails = placed.intersect(below)
    body = placed.cut(below)
    cs = sorted({(round(s.BoundingBox().center.x, 2), round(s.BoundingBox().center.y, 2)) for s in tails.Solids()})
    assert len(cs) == 16 and {x for x, _ in cs} == {-1.27, 1.27}, f"unexpected tail positions {cs}"
    assert {abs(y) for _, y in cs} == {1.27, 3.81, 6.35, 8.89}, f"unexpected tail positions {cs}"
    asm = cq.Assembly(name="ESQ_108_24_G_D")
    asm.add(body, name="body", color=BLACK)
    asm.add(tails, name="tails", color=GOLD)
    asm.save(OUT, exportType="STEP")
    p = placed.BoundingBox()
    print("wrote", os.path.normpath(OUT), f"bbox x {p.xmin:.2f}..{p.xmax:.2f} y {p.ymin:.2f}..{p.ymax:.2f} "
          f"z {p.zmin:.2f}..{p.zmax:.2f}")


if __name__ == "__main__":
    main(sys.argv[1])
